// Turns the committed OpenAPI document into the app's types (ADR 0042, D3). Pure but for the formatter:
// the same document always gives the same three files, so `check:api-types` can compare text.
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

import * as prettier from "prettier";

const ROOT = resolve(import.meta.dirname, "..", "..");
const MOBILE_MANIFEST = join(ROOT, "apps", "mobile", "package.json");
const ERROR_CODES_EXTENSION = "x-sacou-error-codes";
const HASH_LENGTH = 16;

export const GENERATED_FILES = Object.freeze({
  schema: "schema.ts",
  errorCodes: "error-codes.ts",
  contractHash: "contract-hash.ts",
});

const HEADER = [
  "// Generated by scripts/generate-api-types.mjs from apps/api/openapi/v1.json. Do not edit:",
  "// run `pnpm api:contract` after changing the API (ADR 0042).",
  "",
].join("\n");

/** openapi-typescript lives in the app's devDependencies, at the exact version the lockfile pins. */
function loadOpenApiTypescript() {
  return createRequire(MOBILE_MANIFEST)("openapi-typescript");
}

/** The error codes the API declares, refusing a document without them: an empty union would compile anything. */
export function errorCodesOf(document) {
  const codes = document[ERROR_CODES_EXTENSION];
  if (
    !Array.isArray(codes) ||
    codes.length === 0 ||
    !codes.every((code) => typeof code === "string")
  ) {
    throw new Error(`The document has no ${ERROR_CODES_EXTENSION} list of strings.`);
  }
  return codes;
}

/** Same text on Windows and Linux: the hash is over the document with LF line endings. */
export function contractHashOf(documentText) {
  return createHash("sha256")
    .update(documentText.replace(/\r\n/g, "\n"))
    .digest("hex")
    .slice(0, HASH_LENGTH);
}

function errorCodesSource(codes) {
  return [
    HEADER,
    `export const apiErrorCodes = ${JSON.stringify(codes)} as const;`,
    "",
    "export type ApiErrorCode = (typeof apiErrorCodes)[number];",
    "",
  ].join("\n");
}

function contractHashSource(hash) {
  return [
    HEADER,
    "/** Part of the persisted cache's buster: a cache written against another contract is dropped. */",
    `export const apiContractHash = ${JSON.stringify(hash)};`,
    "",
  ].join("\n");
}

async function format(source, fileName, outputDir) {
  const filepath = join(outputDir, fileName);
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(source, { ...options, filepath });
}

/** Returns file name → formatted content, without touching the disk. */
export async function generateApiTypes(documentText, outputDir) {
  const document = JSON.parse(documentText);
  const { default: openapiTS, astToString } = loadOpenApiTypescript();
  const schema = HEADER + astToString(await openapiTS(document));
  const sources = {
    [GENERATED_FILES.schema]: schema,
    [GENERATED_FILES.errorCodes]: errorCodesSource(errorCodesOf(document)),
    [GENERATED_FILES.contractHash]: contractHashSource(contractHashOf(documentText)),
  };
  const entries = await Promise.all(
    Object.entries(sources).map(async ([name, source]) => [
      name,
      await format(source, name, outputDir),
    ]),
  );
  return Object.fromEntries(entries);
}

/** One message per generated file that is missing or differs from what the document gives. */
export function staleFiles(expected, readFile) {
  return Object.entries(expected)
    .filter(([name, content]) => readFile(name) !== content)
    .map(([name]) => `${name} is not what apps/api/openapi/v1.json gives: run \`pnpm api:types\`.`);
}
